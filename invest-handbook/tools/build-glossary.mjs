// Merge tools/glossary/*.json (one file per chapter) into assets/js/glossary-data.js.
// Each file: { "chapter": 25, "terms": [{ "term", "en", "def", "anchor", "aliases": [] }] }
// The chapter that defines a term first (lowest chapter number) owns it.
import { readFile, readdir, writeFile } from "node:fs/promises";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(ROOT, "tools/glossary");
const files = (await readdir(dir)).filter((f) => f.endsWith(".json")).sort();
const glossary = {};
const alias = {};
const clashes = [];
for (const f of files) {
  const data = JSON.parse(await readFile(join(dir, f), "utf8"));
  for (const t of data.terms || []) {
    const key = String(t.term || "").trim();
    if (!key || !t.def) continue;
    const entry = { term: key, en: t.en || "", def: String(t.def).trim(), ch: data.chapter, anchor: t.anchor || "" };
    if (glossary[key]) {
      if (glossary[key].ch !== data.chapter) clashes.push(`${key}: ch${glossary[key].ch} vs ch${data.chapter}`);
      if (glossary[key].ch <= data.chapter) continue;
    }
    glossary[key] = entry;
    for (const a of t.aliases || []) if (a && a !== key) alias[a] = key;
  }
}
for (const a of Object.keys(alias)) if (glossary[a]) delete alias[a];
const sorted = Object.fromEntries(Object.entries(glossary).sort((a, b) => a[1].ch - b[1].ch || a[0].localeCompare(b[0], "zh-Hant")));
const js = `/* 讀通投資 — glossary. Generated by tools/build-glossary.mjs from tools/glossary/*.json; edit those, not this file. */
window.HB = window.HB || {};
HB.glossary = ${JSON.stringify(sorted, null, 1)};
HB.glossaryAlias = ${JSON.stringify(alias, null, 1)};
`;
await writeFile(join(ROOT, "assets/js/glossary-data.js"), js);
console.log(`${Object.keys(sorted).length} terms, ${Object.keys(alias).length} aliases from ${files.length} files`);
if (clashes.length) console.log("defined in more than one chapter (lowest chapter kept):\n  " + clashes.join("\n  "));
